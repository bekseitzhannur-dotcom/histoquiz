function checkMatching() {
 const g = matching[currentTest][matchIndex];
 let points = 0;

 g.items.forEach((_, i) => {
   const value = document.getElementById("match" + i).value;

   if (value !== "" && Number(value) === g.correct[i]) {
     points++;
     document.getElementById("match" + i).style.border = "2px solid green";
   } else {
     document.getElementById("match" + i).style.border = "2px solid red";
   }
 });

 matchScore += points;

 alert(`Дұрыс жұптар: ${points}/${g.items.length}`);

 matchIndex++;
 showMatching();
}




function finishTest() {
    const total = tests[currentTest].length +
        matching[currentTest].reduce((s, g) => s + g.items.length, 0);

    const result = score + matchScore;
    const percent = Math.round((result / total) * 100);

    let name = prompt("Атыңызды енгізіңіз:");

    if (!name || !name.trim()) {
        name = "Қатысушы";
    } else {
        name = name.trim();
    }

    let results = JSON.parse(
        localStorage.getItem("histoResults") || "[]"
    );

    results.push({
        name: name,
        test: currentTest,
        score: result,
        total: total,
        percent: percent,
        date: new Date().toLocaleString("kk-KZ")
    });

    localStorage.setItem("histoResults", JSON.stringify(results));

    const ranking = results
        .filter(r => Number(r.test) === Number(currentTest))
        .sort((a, b) => b.score - a.score);

    const medals = ["🥇", "🥈", "🥉"];

    document.querySelector(".main").innerHTML = `
    <section class="tests-section">
        <h2>🎉 ТЕСТ АЯҚТАЛДЫ!</h2>

        <div class="result-card">
            <h1>${result} / ${total}</h1>
            <h2>${percent}%</h2>
            <p>${name}, нәтижеңіз сақталды!</p>
            <p>Дұрыс жауаптар: ${result}</p>
        </div>

        <h3>🏆 ҚАТЫСУШЫЛАР РЕЙТИНГІ</h3>

        <div class="ranking-list">
            ${ranking.map((r, i) => `
                <div class="ranking-card">
                    <span>${medals[i] || (i + 1) + "."}</span>
                    <strong>${r.name || "Қатысушы"}</strong>
                    <span>${r.score}/${r.total}</span>
                    <span>${r.percent ?? Math.round(r.score / r.total * 100)}%</span>
                </div>
            `).join("")}
        </div>

        <button onclick="location.reload()">БАСТЫ БЕТКЕ →</button>
    </section>`;
}


function showHistory(filter = "", testFilter = "all") {
    const results = JSON.parse(
        localStorage.getItem("histoResults") || "[]"
    );

    const filtered = results.slice().reverse().filter(r => {
        const nameMatch = (r.name || "Қатысушы")
            .toLowerCase()
            .includes(filter.toLowerCase());

        const testMatch = testFilter === "all" ||
            String(r.test) === testFilter;

        return nameMatch && testMatch;
    });

    document.querySelector(".main").innerHTML = `
    <section class="tests-section">
        <h2>📊 НӘТИЖЕЛЕР ТАРИХЫ</h2>

        <input
            id="historySearch"
            type="text"
            placeholder="Қатысушының атын іздеу..."
            oninput="filterHistory()"
        >

        <select id="testFilter" onchange="filterHistory()">
            <option value="all">Барлық тесттер</option>
            <option value="1">Цитология №1</option>
            <option value="2">Цитология №2</option>
        </select>

        <div id="historyList">
            ${filtered.length === 0
                ? "<p>Нәтиже табылмады.</p>"
                : filtered.map(r => `
                    <div class="ranking-card">
                        <strong>${r.name || "Қатысушы"}</strong>
                        <span>Цитология №${r.test}</span>
                        <span>${r.score}/${r.total}</span>
                        <span>${r.percent ?? Math.round(r.score / r.total * 100)}%</span>
                        <small>${r.date || ""}</small>
                    </div>
                `).join("")
            }
        </div>

        <button onclick="location.reload()">БАСТЫ БЕТКЕ →</button>
    </section>`;
}


function filterHistory() {
    const name = document.getElementById("historySearch").value;
    const test = document.getElementById("testFilter").value;

    showHistory(name, test);
}
