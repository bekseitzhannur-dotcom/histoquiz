function chooseAnswer(i) {
 const q = tests[currentTest][questionIndex];
 document.querySelectorAll(".answer").forEach((b,n)=>{
 b.disabled=true;
 if(n===q[2]) b.style.border="2px solid green";
 if(n===i && i!==q[2]) b.style.border="2px solid red";
 });
 if(i===q[2]) {
 score++;
 document.getElementById("feedback").textContent="Дұрыс! +1 балл";
 } else {
 document.getElementById("feedback").textContent="Қате жауап!";
 }
 document.getElementById("next").style.display="inline-block";
}

function nextQuestion() {
 questionIndex++;
 if(questionIndex<tests[currentTest].length) showQuestion();
 else showMatching();
}

